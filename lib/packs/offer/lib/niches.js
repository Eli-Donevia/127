// Archetype from loose words when no niche matched.
const ARCH_WORDS = [
  ['b2b_service', /\b(for (local )?(businesses|brands|shops|restaurants|gyms|contractors|companies|teams|clinics|salons)|agency|b2b|freelanc\w*|clients? who own)\b/i],
  ['teach', /\b(teach\w*|lessons?|classes|training|learn\w*|course|tutor\w*|coach\w*)\b/i],
  ['food', /\b(food|kitchen|bake|cook\w*|chef|drinks?|catering)\b/i],
  ['digital', /\b(digital|download\w*|app|software|saas|online tool|template|ebook)\b/i],
  ['product', /\b(shop|store|brand|products?|handmade|etsy|shopify|sell(ing)? (online|on))\b/i],
  ['personal_service', /\b(session|appointment|studio|beauty|wellness|massage|therap\w*)\b/i],
  ['home_service', /\b(service|clean\w*|repair\w*|install\w*|mobile|home|house|yard)\b/i],
];

function matchNiche(...texts) {
  const hay = texts.filter(Boolean).join(' ');
  if (!hay.trim()) return null;
  return NICHES.find((n) => n.re.test(hay)) || null;
}

function archetypeOf(...texts) {
  const niche = matchNiche(...texts);
  if (niche) return niche.arch;
  const hay = texts.filter(Boolean).join(' ');
  const hit = ARCH_WORDS.find(([, re]) => re.test(hay));
  return hit ? hit[0] : 'home_service';
}

// A niche merged over its archetype: every field is filled.
function profileFor(...texts) {
  const niche = matchNiche(...texts);
  const arch = niche ? niche.arch : archetypeOf(...texts);
  const base = ARCH[arch];
  const merged = { ...base, ...(niche || {}), arch, nicheId: niche ? niche.id : null, archLabel: base.label };
  for (const k of ['attraction', 'upsell', 'downsell', 'continuity']) merged[k] = { ...base[k], ...((niche && niche[k]) || {}) };
  merged.promise = { ...base.promise, ...((niche && niche.promise) || {}) };
  merged.checklist = (niche && niche.checklist) || base.checklist;
  merged.calc = (niche && niche.calc) || base.calc;
  merged.template = (niche && niche.template) || base.template;
  return merged;
}

