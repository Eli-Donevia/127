#!/usr/bin/env node
// Builds the draft legal page partials from Legal's Markdown, with the same converter as the membership terms:
//
//   node scripts/build-legal-pages.js [path/to/legal]      (default /mnt/project-files/legal)
//
//   views/partials/cookie-notice.ejs        from 08-cookie-notice.md Part A        (/cookies)
//   views/partials/earnings-disclaimer.ejs  from 05-earnings-disclaimer.md Part A  (/earnings-disclaimer)
//
// Only Part A goes in (it stops at "# Part B"); the draft note above it and the drafting notes are left out.
// The pages show a draft banner until COOKIE_NOTICE_LIVE / EARNINGS_DISCLAIMER_LIVE is true (Eli's approval).
// Re-run whenever Legal updates the source, and commit the generated partials.

const fs = require('fs');
const path = require('path');
const { convert } = require('./build-membership-terms');

const DIR = process.argv[2] || '/mnt/project-files/legal';
const PAGES = [
  { src: '08-cookie-notice.md', out: 'cookie-notice.ejs' },
  { src: '05-earnings-disclaimer.md', out: 'earnings-disclaimer.ejs' },
];

// "# Part A. Cookie Notice (public page at /cookies)" through the line before "# Part B", titled "Cookie Notice".
function partA(md) {
  const lines = md.replace(/\r\n/g, '\n').split('\n');
  const start = lines.findIndex((l) => /^# Part A\b/i.test(l));
  if (start < 0) throw new Error('No "# Part A" heading found in the source.');
  let end = lines.findIndex((l, i) => i > start && (/^# Part B\b/i.test(l) || /^#+ Drafting notes/i.test(l)));
  if (end < 0) end = lines.length;
  const body = lines.slice(start, end);
  body[0] = '# ' + body[0].replace(/^# Part A\.?\s*/i, '').replace(/\s*\(public page at [^)]*\)\s*$/i, '');
  while (body.length && /^(---|\s*)$/.test(body[body.length - 1])) body.pop();
  return body;
}

function build(md, src) {
  return (
    `<%# Generated by scripts/build-legal-pages.js from Legal's legal/${src} (Part A). Edit the source and re-run; don't edit by hand. %>\n` +
    `<div class="legal-md">\n${convert(partA(md))}\n</div>\n`
  );
}

if (require.main === module) {
  for (const p of PAGES) {
    const html = build(fs.readFileSync(path.join(DIR, p.src), 'utf8'), p.src);
    const out = path.join(__dirname, '..', 'views', 'partials', p.out);
    fs.writeFileSync(out, html);
    console.log(`Wrote ${path.relative(process.cwd(), out)} (${html.length} bytes)`);
  }
}

module.exports = { build, partA };
